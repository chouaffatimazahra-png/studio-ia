let LANG = (() => {
  const saved = localStorage.getItem("lang");
  if (saved && I18N[saved]) return saved;
  // par défaut : français (arabe si le téléphone du visiteur est en arabe)
  return (navigator.language || "").startsWith("ar") ? "ar" : "fr";
})();

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.fr[key] ?? key;
  if (vars && typeof s === "string") for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
  return s;
}

function applyStaticI18n() {
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANG === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll("#langSwitch [data-lang]").forEach((b) => b.classList.toggle("active", b.dataset.lang === LANG));
}
